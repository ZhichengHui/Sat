#!/usr/bin/env bash
# Usage: tools/regen.sh
# Regenerates urust/ from core/src/lib.rs with the AutoCorrode Rust front end at the newest commit of
# its master branch (ZhichengHui/AutoCorrodeRustFrontEnd): the front end clone is updated to
# origin/master and built, then urust/ is replaced by its output. The front end is never pinned:
# the translation always follows the newest front end, and CI checks that urust/ is what it
# produces.
#   URUST_FRONTEND  a clone of the front end that this script may update and build
#                   (default on the compute server: $RT/AutoCorrodeRustFrontEnd; elsewhere required,
#                   and not a working copy you edit)
# A lock on the clone serialises concurrent runs (pod agents).
set -euo pipefail
HERE=$(cd "$(dirname "$0")/.." && pwd)
NAME=$(sed -n 's/^session "\([A-Za-z0-9_]*\)".*/\1/p' "$HERE/urust/ROOT" | head -1)
RT=/disk/scratch/$(id -un)
if [ -d "$RT/rust" ]; then
  FE=${URUST_FRONTEND:-$RT/AutoCorrodeRustFrontEnd}
  export RUSTUP_HOME=${RUSTUP_HOME:-$RT/rust/rustup} CARGO_HOME=${CARGO_HOME:-$RT/rust/cargo}
  export PATH=$CARGO_HOME/bin:$PATH
else
  FE=${URUST_FRONTEND:?set URUST_FRONTEND to a clone of the front end that this script may update}
  export RUSTUP_HOME=${RUSTUP_HOME:-$HOME/.rustup}
fi
exec 9>"$FE/.regen.lock"
flock 9
git -C "$FE" fetch -q origin master
git -C "$FE" checkout -q --detach FETCH_HEAD
(cd "$FE" && cargo build --release -q)
rm -rf "$HERE/urust.new"
"$FE/scripts/urust-frontend.sh" --out "$HERE/urust.new" --name "$NAME" "$HERE/core/src/lib.rs" > /dev/null
rm -rf "$HERE/urust"
mv "$HERE/urust.new" "$HERE/urust"
echo "urust/ regenerated by the front end at $(git -C "$FE" rev-parse --short HEAD)"
